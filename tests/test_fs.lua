local H = require("helper")
local Fs = require("core.fs")

local function tmpdir()
    local p = io.popen("mktemp -d")
    local d = p:read("*l")
    p:close()
    return d
end

H.test("fs write creates parent dirs and read returns the content", function()
    local d = tmpdir()
    H.eq(Fs.write(d .. "/a/b/c.txt", "hello"), true)
    H.eq(Fs.read(d .. "/a/b/c.txt"), "hello")
end)

H.test("fs read of a missing file returns nil", function()
    H.eq(Fs.read(tmpdir() .. "/nada"), nil)
end)

H.test("fs write overwrites and handles binary content", function()
    local d = tmpdir()
    Fs.write(d .. "/x.bin", "old")
    Fs.write(d .. "/x.bin", "a\0b\255")
    H.eq(Fs.read(d .. "/x.bin"), "a\0b\255")
end)

H.test("fs list returns sorted recursive relative file paths", function()
    local d = tmpdir()
    Fs.write(d .. "/z.lua", "1")
    Fs.write(d .. "/core/a.lua", "2")
    Fs.write(d .. "/core/deep/b.lua", "3")
    H.eq(Fs.list(d), { "core/a.lua", "core/deep/b.lua", "z.lua" })
    H.eq(Fs.list(d .. "/nada"), {})
end)

H.test("fs exists, remove and remove_tree", function()
    local d = tmpdir()
    Fs.write(d .. "/a/one", "1")
    Fs.write(d .. "/a/two", "2")
    H.eq(Fs.exists(d .. "/a/one"), true)
    H.eq(Fs.remove(d .. "/a/one"), true)
    H.eq(Fs.exists(d .. "/a/one"), false)
    H.eq(Fs.exists(d .. "/a/two"), true)
    H.eq(Fs.remove_tree(d .. "/a"), true)
    H.eq(Fs.exists(d .. "/a/two"), false)
    H.eq(Fs.remove_tree(d .. "/nada"), true)
end)

H.test("fs refuses paths with quotes or newlines", function()
    local d = tmpdir()
    local ok = Fs.write(d .. "/it's.txt", "x")
    H.eq(ok, nil)
    H.eq(Fs.list(d .. "/a'b"), {})
    H.eq(Fs.remove_tree("x'; rm -rf ~ '"), nil)
end)
