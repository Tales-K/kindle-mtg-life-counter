local H = require("helper")
local Game = require("core.game")
local Actions = require("core.actions")

local function fake_store()
    local s = { saves = 0 }
    function s:save(t) self.saves = self.saves + 1; self.last = t; return true end
    return s
end

H.test("plus zone adds 1 and saves once", function()
    local g, s = Game.new(2, 40), fake_store()
    H.eq(Actions.apply(g, s, 1, "plus", false), true)
    H.eq(g.players[1].life, 41)
    H.eq(s.saves, 1)
    H.eq(s.last, g:to_table())
end)

H.test("minus zone subtracts 1", function()
    local g, s = Game.new(2, 40), fake_store()
    Actions.apply(g, s, 2, "minus", false)
    H.eq(g.players[2].life, 39)
    H.eq(g.players[1].life, 40)
end)

H.test("big plus changes life by exactly 10", function()
    local g, s = Game.new(2, 40), fake_store()
    Actions.apply(g, s, 1, "plus", true)
    H.eq(g.players[1].life, 50)
    H.eq(s.saves, 1)
end)

H.test("big minus on poison subtracts 10 floored at 0", function()
    local g, s = Game.new(2, 40), fake_store()
    g:adjust_poison(1, 4)
    Actions.apply(g, s, 1, "poison_minus", true)
    H.eq(g.players[1].poison, 0)
end)

H.test("poison plus adds 1", function()
    local g, s = Game.new(3, 40), fake_store()
    Actions.apply(g, s, 3, "poison_plus", false)
    H.eq(g.players[3].poison, 1)
end)

H.test("zones without an action do nothing and do not save", function()
    local g, s = Game.new(2, 40), fake_store()
    for _, z in ipairs({ "life", "poison_value", "commander" }) do
        H.eq(Actions.apply(g, s, 1, z, false), false)
    end
    H.eq(Actions.apply(g, s, 1, nil, false), false)
    H.eq(s.saves, 0)
    H.eq(g.players[1].life, 40)
end)

H.test("unknown player index does nothing", function()
    local g, s = Game.new(2, 40), fake_store()
    H.eq(Actions.apply(g, s, 5, "plus", false), false)
    H.eq(s.saves, 0)
end)

H.test("many quick taps each count once", function()
    local g, s = Game.new(2, 40), fake_store()
    for _ = 1, 25 do Actions.apply(g, s, 1, "minus", false) end
    H.eq(g.players[1].life, 15)
    H.eq(s.saves, 25)
end)

H.test("on_panel: tap on an opponent's minimap square opens his damage field and changes nothing", function()
    local g, s = Game.new(4, 40), fake_store()
    g:adjust_commander(1, 3, 5)
    local before = g:to_table()
    local result, field = Actions.on_panel(g, s, 1, { zone = "cmd", source = 4 }, false)
    H.eq(result, "open")
    H.eq(field, { kind = "commander", source = 4 })
    H.eq(g:to_table(), before)
    H.eq(s.saves, 0)
end)

H.test("on_panel: tap on the poison drop opens the poison field and changes nothing", function()
    local g, s = Game.new(4, 40), fake_store()
    local before = g:to_table()
    local result, field = Actions.on_panel(g, s, 2, { zone = "poison" }, false)
    H.eq(result, "open")
    H.eq(field, { kind = "poison" })
    H.eq(g:to_table(), before)
    H.eq(s.saves, 0)
end)

H.test("on_panel: own square, holding the minimap or the drop do nothing", function()
    local g, s = Game.new(4, 40), fake_store()
    local before = g:to_table()
    H.eq(Actions.on_panel(g, s, 1, { zone = "cmd", source = "self" }, false), nil)
    H.eq(Actions.on_panel(g, s, 1, { zone = "cmd", source = 3 }, true), nil)
    H.eq(Actions.on_panel(g, s, 1, { zone = "poison" }, true), nil)
    H.eq(g:to_table(), before)
    H.eq(s.saves, 0)
end)

H.test("on_panel: halves change life, nil zone does nothing", function()
    local g, s = Game.new(2, 40), fake_store()
    H.eq(Actions.on_panel(g, s, 2, { zone = "plus" }, false), "changed")
    H.eq(Actions.on_panel(g, s, 2, { zone = "minus" }, true), "changed")
    H.eq(g.players[2].life, 31)
    H.eq(Actions.on_panel(g, s, 2, nil, false), nil)
    H.eq(s.saves, 2)
end)

H.test("commander actions: plus adds damage and removes life, saves once", function()
    local g, s = Game.new(3, 40), fake_store()
    H.eq(Actions.apply_commander(g, s, 1, 2, 1, false), true)
    H.eq(g.players[1].cmd[2], 1)
    H.eq(g.players[1].life, 39)
    H.eq(s.saves, 1)
end)

H.test("commander actions: big minus floors at zero and returns only dealt life", function()
    local g, s = Game.new(3, 40), fake_store()
    g:adjust_commander(1, 2, 4)
    H.eq(Actions.apply_commander(g, s, 1, 2, -1, true), true)
    H.eq(g.players[1].cmd[2], 0)
    H.eq(g.players[1].life, 40)
end)

H.test("commander actions: minus at zero changes nothing and does not save", function()
    local g, s = Game.new(3, 40), fake_store()
    H.eq(Actions.apply_commander(g, s, 1, 2, -1, false), false)
    H.eq(s.saves, 0)
    H.eq(g.players[1].life, 40)
end)

H.test("commander actions: source equal to target does nothing", function()
    local g, s = Game.new(3, 40), fake_store()
    H.eq(Actions.apply_commander(g, s, 1, 1, 1, false), false)
    H.eq(s.saves, 0)
end)

local CMD = { kind = "commander", source = 4 }
local POISON = { kind = "poison" }

H.test("on_field commander: tap is +-1 and hold +-10 on that opponent only, life follows", function()
    local g, s = Game.new(4, 40), fake_store()
    H.eq(Actions.on_field(g, s, 1, CMD, "plus", false), true)
    H.eq(Actions.on_field(g, s, 1, CMD, "plus", true), true)
    H.eq(g.players[1].cmd[4], 11)
    H.eq(g.players[1].life, 29)
    H.eq(Actions.on_field(g, s, 1, CMD, "minus", false), true)
    H.eq(g.players[1].cmd[4], 10)
    H.eq(g.players[1].life, 30)
    H.eq(g.players[1].cmd[2], nil)
    H.eq(s.saves, 3)
end)

H.test("on_field poison: tap is +-1, holding changes nothing", function()
    local g, s = Game.new(4, 40), fake_store()
    H.eq(Actions.on_field(g, s, 1, POISON, "plus", false), true)
    H.eq(Actions.on_field(g, s, 1, POISON, "plus", false), true)
    H.eq(Actions.on_field(g, s, 1, POISON, "minus", false), true)
    H.eq(g.players[1].poison, 1)
    H.eq(Actions.on_field(g, s, 1, POISON, "plus", true), false)
    H.eq(Actions.on_field(g, s, 1, POISON, "minus", true), false)
    H.eq(g.players[1].poison, 1)
    H.eq(g.players[1].life, 40)
    H.eq(s.saves, 3)
end)

H.test("on_field: OK, nil and unknown actions change nothing", function()
    local g, s = Game.new(4, 40), fake_store()
    for _, f in ipairs({ CMD, POISON }) do
        H.eq(Actions.on_field(g, s, 1, f, "ok", false), false)
        H.eq(Actions.on_field(g, s, 1, f, nil, false), false)
        H.eq(Actions.on_field(g, s, 1, f, "ok", true), false)
    end
    H.eq(g:to_table(), Game.new(4, 40):to_table())
    H.eq(s.saves, 0)
end)

H.test("revive by commander through the field: 21 is out, -1 is back with +1 life, 0 restores the life", function()
    local g, s = Game.new(4, 40), fake_store()
    for _ = 1, 2 do Actions.on_field(g, s, 1, CMD, "plus", true) end
    Actions.on_field(g, s, 1, CMD, "plus", false)
    H.eq(g.players[1].cmd[4], 21)
    H.eq(g.players[1].life, 19)
    H.eq(g:status(1), "commander")
    H.eq(Actions.on_field(g, s, 1, CMD, "minus", false), true)
    H.eq(g:status(1), nil)
    H.eq(g.players[1].life, 20)
    Actions.on_field(g, s, 1, CMD, "minus", true)
    Actions.on_field(g, s, 1, CMD, "minus", true)
    H.eq(g.players[1].cmd[4], 0)
    H.eq(g.players[1].life, 40)
    H.eq(g:status(1), nil)
end)

H.test("revive by poison through the field: 10 is out, 9 is back, 0 is clean", function()
    local g, s = Game.new(4, 40), fake_store()
    for _ = 1, 10 do Actions.on_field(g, s, 2, POISON, "plus", false) end
    H.eq(g:status(2), "poison")
    H.eq(Actions.on_field(g, s, 2, POISON, "minus", false), true)
    H.eq(g.players[2].poison, 9)
    H.eq(g:status(2), nil)
    for _ = 1, 9 do Actions.on_field(g, s, 2, POISON, "minus", false) end
    H.eq(g.players[2].poison, 0)
    H.eq(g:status(2), nil)
    H.eq(g.players[2].life, 40)
end)
