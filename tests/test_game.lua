local H = require("helper")
local Game = require("core.game")

H.test("new rejects 1 and 7 players", function()
    H.raises(function() Game.new(1, 40) end)
    H.raises(function() Game.new(7, 40) end)
end)

H.test("new rejects starting life below 1", function()
    H.raises(function() Game.new(4, 0) end)
end)

H.test("new starts everyone at starting life with zero poison", function()
    local g = Game.new(4, 40)
    H.eq(g.player_count, 4)
    for i = 1, 4 do
        H.eq(g.players[i].life, 40)
        H.eq(g.players[i].poison, 0)
    end
end)

H.test("adjust_life subtracts and adds and allows negative", function()
    local g = Game.new(2, 40)
    g:adjust_life(1, -50)
    H.eq(g.players[1].life, -10)
    g:adjust_life(1, 3)
    H.eq(g.players[1].life, -7)
    H.eq(g.players[2].life, 40)
end)

H.test("adjust_poison floors at 0", function()
    local g = Game.new(2, 40)
    g:adjust_poison(1, -3)
    H.eq(g.players[1].poison, 0)
    g:adjust_poison(1, 4)
    H.eq(g.players[1].poison, 4)
end)

H.test("commander damage also removes life", function()
    local g = Game.new(3, 40)
    local applied = g:adjust_commander(1, 2, 7)
    H.eq(applied, 7)
    H.eq(g.players[1].cmd[2], 7)
    H.eq(g.players[1].life, 33)
end)

H.test("commander decrement returns the life", function()
    local g = Game.new(3, 40)
    g:adjust_commander(1, 2, 7)
    local applied = g:adjust_commander(1, 2, -3)
    H.eq(applied, -3)
    H.eq(g.players[1].cmd[2], 4)
    H.eq(g.players[1].life, 36)
end)

H.test("commander decrement at 0 changes nothing", function()
    local g = Game.new(3, 40)
    local applied = g:adjust_commander(1, 2, -5)
    H.eq(applied, 0)
    H.eq(g.players[1].life, 40)
    H.eq(g.players[1].cmd[2] or 0, 0)
end)

H.test("commander decrement beyond damage only returns what was dealt", function()
    local g = Game.new(3, 40)
    g:adjust_commander(1, 2, 2)
    local applied = g:adjust_commander(1, 2, -5)
    H.eq(applied, -2)
    H.eq(g.players[1].life, 40)
end)

H.test("commander from self errors", function()
    local g = Game.new(3, 40)
    H.raises(function() g:adjust_commander(1, 1, 1) end)
end)

H.test("status is commander at 21 from one source", function()
    local g = Game.new(3, 99)
    g:adjust_commander(1, 2, 21)
    H.eq(g:status(1), "commander")
end)

H.test("status is not commander for 11 plus 10 from two sources", function()
    local g = Game.new(3, 99)
    g:adjust_commander(1, 2, 11)
    g:adjust_commander(1, 3, 10)
    H.eq(g:status(1), nil)
end)

H.test("status is poison at 10", function()
    local g = Game.new(2, 40)
    g:adjust_poison(1, 9)
    H.eq(g:status(1), nil)
    g:adjust_poison(1, 1)
    H.eq(g:status(1), "poison")
end)

H.test("status priority is life over poison over commander", function()
    local g = Game.new(3, 40)
    g:adjust_poison(1, 10)
    g:adjust_commander(1, 2, 21)
    H.eq(g:status(1), "poison")
    g:adjust_life(1, -100)
    H.eq(g:status(1), "life")
end)

H.test("to_table and from_table round-trip", function()
    local g = Game.new(4, 30)
    g:adjust_life(2, -5)
    g:adjust_poison(3, 2)
    g:adjust_commander(1, 4, 6)
    local g2 = assert(Game.from_table(g:to_table()))
    H.eq(g2:to_table(), g:to_table())
    H.eq(g2.players[1].cmd[4], 6)
end)

H.test("from_table rejects bad data", function()
    H.eq(Game.from_table(nil), nil)
    H.eq(Game.from_table({}), nil)
    local g = Game.new(2, 40)
    local t = g:to_table()
    t.player_count = 9
    H.eq(Game.from_table(t), nil)
    t = g:to_table()
    t.players[1].poison = -1
    H.eq(Game.from_table(t), nil)
    t = g:to_table()
    t.players[2] = nil
    H.eq(Game.from_table(t), nil)
    t = g:to_table()
    t.players[1].life = "x"
    H.eq(Game.from_table(t), nil)
end)
